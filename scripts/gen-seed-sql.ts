// Generates supabase/seed.sql from src/data/seed.ts so the app and the database share one source of truth.
// Run: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { seedConfig as c } from '../src/data/seed';

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (a: number[]) => `'{${a.join(',')}}'`;
const lines: string[] = ['-- Generated by scripts/gen-seed-sql.ts. Do not edit by hand.', 'begin;'];

for (const p of c.pods) lines.push(`insert into pods (id, name) values (${q(p.id)}, ${q(p.name)});`);
for (const e of c.employees)
  lines.push(
    `insert into employees (id, name, pod_id, role, preferred_off_days, max_consecutive) values ` +
      `(${q(e.id)}, ${q(e.name)}, ${q(e.podId)}, ${q(e.role)}, ${arr(e.preferredOffDays)}, ${e.maxConsecutive});`,
  );
for (const p of c.pods) lines.push(`update pods set lead_employee_id = ${q(p.leadId)} where id = ${q(p.id)};`);
for (const b of c.brands)
  lines.push(`insert into brands (id, name, pod_id) values (${q(b.id)}, ${q(b.name)}, ${q(b.podId)});`);
for (const p of c.processes) {
  lines.push(
    `insert into processes (id, brand_id, name, calendar_type, min_staff) values ` +
      `(${q(p.id)}, ${q(p.brandId)}, ${q(p.name)}, ${q(p.calendar)}, ${p.minStaff});`,
  );
  for (const [d, n] of Object.entries(p.minStaffByDow ?? {}))
    lines.push(`insert into coverage_rules (process_id, day_of_week, min_staff) values (${q(p.id)}, ${d}, ${n});`);
  for (const [date, n] of Object.entries(p.dateOverrides ?? {}))
    lines.push(`insert into coverage_rules (process_id, on_date, min_staff) values (${q(p.id)}, ${q(date)}, ${n});`);
}
for (const a of c.assignments)
  lines.push(
    `insert into assignments (employee_id, process_id, is_backup) values ` +
      `(${q(a.employeeId)}, ${q(a.processId)}, ${a.isBackup});`,
  );
for (const h of c.holidays) lines.push(`insert into holidays (date, name) values (${q(h.date)}, ${q(h.name)});`);
for (const l of c.leaves)
  lines.push(
    `insert into leaves (id, employee_id, start_date, end_date, type) values ` +
      `(${q(l.id)}, ${q(l.employeeId)}, ${q(l.start)}, ${q(l.end)}, ${q(l.type)});`,
  );
lines.push('commit;', '');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'));
console.log(`seed.sql written: ${c.employees.length} employees, ${c.brands.length} brands, ${c.processes.length} processes`);
